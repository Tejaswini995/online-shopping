CREATE DATABASE IF NOT EXISTS shopeasy;
USE shopeasy;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
 role ENUM('customer','admin') NOT NULL DEFAULT 'customer'
);
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255) NOT NULL,
 description TEXT, category VARCHAR(120), price DECIMAL(10,2) NOT NULL,
 stock INT NOT NULL DEFAULT 0, image TEXT,
 CHECK (price >= 0), CHECK (stock >= 0)
);
CREATE TABLE IF NOT EXISTS orders (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL,
 address TEXT NOT NULL, total DECIMAL(12,2) NOT NULL,
 status VARCHAR(40) NOT NULL DEFAULT 'Placed',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS order_items (
 id INT AUTO_INCREMENT PRIMARY KEY, order_id INT NOT NULL,
 product_id INT NOT NULL, name VARCHAR(255) NOT NULL,
 price DECIMAL(10,2) NOT NULL, quantity INT NOT NULL,
 FOREIGN KEY (order_id) REFERENCES orders(id),
 FOREIGN KEY (product_id) REFERENCES products(id)
);
